import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const rulesDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "rules"
);

const HEADER_RE = /^\s*(engine|language)\b/;
const IGNORED_GROUPS = new Set(["node_modules"]);

function parse(source) {
  const lines = source.split("\n");
  const header = [];
  let i = 0;
  while (
    i < lines.length &&
    (HEADER_RE.test(lines[i]) || lines[i].trim() === "")
  ) {
    if (HEADER_RE.test(lines[i])) {
      header.push(lines[i].trim());
    }
    i += 1;
  }
  return { body: lines.slice(i).join("\n").trim(), header: header.join("\n") };
}

export function getGroups() {
  return readdirSync(rulesDir, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        !entry.name.startsWith(".") &&
        !IGNORED_GROUPS.has(entry.name)
    )
    .map((entry) => entry.name)
    .sort();
}

export function getRuleFiles({ group }) {
  const groupDir = join(rulesDir, group);
  return readdirSync(groupDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".grit"))
    .map((entry) => {
      const filePath = join(groupDir, entry.name);
      return {
        label: `${group}/${entry.name}`,
        name: entry.name,
        source: readFileSync(filePath, "utf8"),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

/*
 * Each individual rule file starts with one or more directive lines (engine
 * and/or language) followed by a single top-level pattern. To merge them into
 * one file we emit the shared directives once and wrap every pattern body as an
 * arm of a top-level or block. Biome requires all merged rules to share the
 * same language, so divergent directives are a hard error rather than a silent
 * mismerge.
 */
export function writeBundle({
  files,
  generatorScript,
  outFile,
  sourceDescription,
}) {
  if (files.length === 0) {
    throw new Error(`No source .grit rules found in ${sourceDescription}`);
  }

  let sharedHeader = null;
  const arms = [];

  for (const file of files) {
    const { header, body } = parse(file.source);
    if (sharedHeader === null) {
      sharedHeader = header;
    } else if (header !== sharedHeader) {
      throw new Error(
        `Rule "${file.label}" declares a different language/engine header than the others.\n` +
          `Expected:\n${sharedHeader}\nGot:\n${header}\n` +
          `All rules merged into ${outFile} must target the same language.`
      );
    }
    if (body === "") {
      throw new Error(`Rule "${file.label}" has no pattern body.`);
    }
    arms.push(
      body
        .split("\n")
        .map((line) => (line ? `  ${line}` : line))
        .join("\n")
    );
  }

  const banner =
    `// AUTO-GENERATED by scripts/${generatorScript} — do not edit.\n` +
    `// Combines rules from ${sourceDescription}. Run pnpm build to regenerate.\n`;
  const output = `${banner}\n${sharedHeader}\n\nor {\n${arms.join(",\n")}\n}\n`;

  writeFileSync(outFile, output);
  console.log(
    `Wrote ${outFile} (${files.length} rules: ${files.map((file) => file.name).join(", ")})`
  );
}
